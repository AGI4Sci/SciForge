export function getNeedClassification(id: string): NeedClassification {
  return needClassifications[id];
}

export function flattenNeedClassification(id: string) {
  return Object.values(getNeedClassification(id)).flat();
}

export function getTaxonomyLabel(code: string) {
  for (const dimension of taxonomyDimensions) {
    const value = dimension.values.find(([candidate]) => candidate === code);
    if (value) return value[1];
  }
  return code;
}

