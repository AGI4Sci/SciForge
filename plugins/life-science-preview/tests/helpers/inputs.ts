const textEncoder = new TextEncoder()

/**
 * Minimal classic little-endian baseline TIFF with a single uncompressed RGB
 * strip — the domain-supported minimal binary input (the bioimaging engine
 * decodes baseline TIFF only; PNG input is rejected upstream by the provider
 * extension gate, so a "tiny real PNG fixture" is not a domain-supported
 * case). Structure mirrors workspace-bioimaging's engine test builder.
 */
export function makeUncompressedRgbTiff(
  width: number,
  height: number,
  pixels: Uint8Array
): Uint8Array {
  if (pixels.byteLength !== width * height * 3) {
    throw new Error('Pixel payload must be width * height * 3 bytes of RGB.')
  }
  const entryCount = 9
  const ifdOffset = 8
  const ifdByteLength = 2 + entryCount * 12 + 4
  const bitsOffset = ifdOffset + ifdByteLength
  const pixelOffset = bitsOffset + 6
  const bytes = new Uint8Array(pixelOffset + pixels.byteLength)
  const view = new DataView(bytes.buffer)

  bytes[0] = 'I'.charCodeAt(0)
  bytes[1] = 'I'.charCodeAt(0)
  view.setUint16(2, 42, true)
  view.setUint32(4, ifdOffset, true)
  view.setUint16(ifdOffset, entryCount, true)

  const writeEntry = (index: number, tag: number, type: number, count: number, value: number) => {
    const entryOffset = ifdOffset + 2 + index * 12
    view.setUint16(entryOffset, tag, true)
    view.setUint16(entryOffset + 2, type, true)
    view.setUint32(entryOffset + 4, count, true)
    view.setUint32(entryOffset + 8, value, true)
  }
  writeEntry(0, 256, 4, 1, width)
  writeEntry(1, 257, 4, 1, height)
  writeEntry(2, 258, 3, 3, bitsOffset)
  writeEntry(3, 259, 3, 1, 1)
  writeEntry(4, 262, 3, 1, 2)
  writeEntry(5, 273, 4, 1, pixelOffset)
  writeEntry(6, 277, 3, 1, 3)
  writeEntry(7, 278, 4, 1, height)
  writeEntry(8, 279, 4, 1, pixels.byteLength)
  view.setUint32(ifdOffset + 2 + entryCount * 12, 0, true)

  view.setUint16(bitsOffset, 8, true)
  view.setUint16(bitsOffset + 2, 8, true)
  view.setUint16(bitsOffset + 4, 8, true)
  bytes.set(pixels, pixelOffset)
  return bytes
}

export function tinyRgbTiffFixture(): Uint8Array {
  // 2x2 RGB: red, green, blue, white.
  return makeUncompressedRgbTiff(2, 2, new Uint8Array([
    255, 0, 0, 0, 255, 0,
    0, 0, 255, 255, 255, 255
  ]))
}

export function toBytes(value: string | Uint8Array): Uint8Array {
  return typeof value === 'string' ? textEncoder.encode(value) : value
}

export function makeFileState(input: {
  workspaceRoot: string
  path: string
  relativePath?: string
  mimeType?: string
}): WorkspacePreviewFileState {
  return {
    workspaceRoot: input.workspaceRoot,
    path: input.path,
    ...(input.relativePath ? { relativePath: input.relativePath } : {}),
    ...(input.mimeType ? { mimeType: input.mimeType } : {})
  }
}

export function makeSession(input: {
  manifestId: string
  modality: WorkspacePreviewSession['modality']
  workspaceRoot: string
  path: string
}): WorkspacePreviewSession {
  return {
    id: `session-${input.manifestId}`,
    pluginId: input.manifestId,
    workspaceRoot: input.workspaceRoot,
    path: input.path,
    modality: input.modality,
    mode: 'preview',
    openedAt: '2026-10-17T00:00:00.000Z',
    updatedAt: '2026-10-17T00:00:00.000Z'
  }
}

export function makeActionInput(actionId: string, input: Record<string, unknown> = {}): WorkspacePreviewPluginActionInput {
  return { actionId, input }
}

/** Builds the standard provider observation input for a slot + workspace file. */
export function makeObservationInput(
  contract: typeof CONTRACTS.molecular,
  workspaceRoot: string,
  path: string,
  relativePath?: string
) {
  return {
    session: makeSession({
      manifestId: contract.manifest.id,
      modality: contract.manifest.modality,
      workspaceRoot,
      path
    }),
    manifest: contract.manifest,
    file: makeFileState({ workspaceRoot, path, relativePath })
  }
}
