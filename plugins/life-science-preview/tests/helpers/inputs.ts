function contractFor(pluginId: string) {
  const contract = LIFE_SCIENCE_WORKSPACE_PREVIEW_PLUGIN_CONTRACTS.find(
    (candidate) => candidate.manifest.id === pluginId
  )
  if (!contract) throw new Error(`Test helper could not find contract for ${pluginId}.`)
  return contract
}

