// Trusted release-maintainer operation, never part of runtime discovery.
import assert from 'node:assert/strict'
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync, mkdirSync, readdirSync, lstatSync } from 'node:fs'
import { resolve, join } from 'node:path'
import yaml from 'js-yaml'
import { DSH_SAFETY_PATCH, validateDshComposedConfig, canonicalizeDshComposedConfig } from '../src/deployment.js'
import { createPinnedDshDeployment } from '../src/trusted-deployment.js'
import { DSH_MODEL_ROUTER_PATCH } from '../src/model-router.js'

const artifact = resolve(process.argv[2])
const source = resolve(process.argv[3])
const release = new URL('../docs/release-review/', import.meta.url)
const schema = yaml.DEFAULT_SCHEMA.extend([new yaml.Type('tag:yaml.org,2002:js', {kind:'scalar', construct: value => ({__jsExpr:value})})])
const parse = (text: string) => yaml.load(text, {schema}) as Record<string, any>[]
const sha = (bytes: string | Buffer) => createHash('sha256').update(bytes).digest('hex')
const reviewed = parse(readFileSync(new URL('default-acp.yml', release), 'utf8'))
// Independent static reconstruction: only the two reviewed shipped bundle files.
const rows: Record<string, any>[] = []
for (const file of ['packages/bundle/base/cordis.patch.yml', 'packages/bundle/acp-app/cordis.patch.yml']) {
  for (const patch of parse(readFileSync(join(source, file), 'utf8'))) {
    if (patch.insert) { assert.deepEqual(Object.keys(patch), ['insert']); rows.push(...patch.insert) }
    else { const row = rows.find(row => row.id === patch.id); assert.ok(row); Object.assign(row, patch) }
  }
}
assert.deepEqual(rows, reviewed, 'Official static owners/config changed: explicit new review required')
const files: Record<string, string> = {}
function walk(dir: string, prefix='') {
  for (const item of readdirSync(dir, {withFileTypes:true}).sort((a,b) => a.name.localeCompare(b.name))) {
    const path = join(dir,item.name), key = prefix + item.name
    const stat = lstatSync(path)
    assert.equal(stat.isSymbolicLink(), false)
    if (item.isDirectory()) walk(path,key+'/')
    else { assert.ok(item.isFile()); assert.equal(stat.nlink,1); files[key] = sha(readFileSync(path)) }
  }
}
walk(artifact)
const manifest = JSON.parse(readFileSync(artifact+'.files.json','utf8'))
assert.deepEqual(files,manifest,'Staged closure differs from build manifest')
const state = resolve(artifact,'../../../../release-probe')
for (const path of [state,join(state,'tmp'),join(state,'dsh')]) mkdirSync(path,{recursive:true,mode:0o700})
const env = {PATH:'/usr/bin:/bin',HOME:state,TMPDIR:join(state,'tmp'),DSH_HOME:join(state,'dsh'),DSH_TELEMETRY_MODE:'DISABLED',DSH_TELEMETRY_DISABLED:'1',LANG:'en_US.UTF-8',LC_ALL:'en_US.UTF-8'}
const run = (args: string[]) => execFileSync(join(artifact,'dsh'),args,{cwd:state,env,encoding:'utf8',timeout:30000,maxBuffer:4*1024*1024})
assert.equal(run(['--version']).trim(),'0.2.0-rc.2')
const help = run(['acp','--help']); assert.match(help,/Agent Client Protocol/)
writeFileSync(join(state,'safety.yml'),yaml.dump(JSON.parse(DSH_SAFETY_PATCH)) + DSH_MODEL_ROUTER_PATCH,{mode:0o600})
const original = run(['acp','--dump-config']); assert.deepEqual(parse(original),reviewed)
const config = run(['acp','--patch',join(state,'safety.yml'),'--dump-config'])
const expected = structuredClone(reviewed)
// Independently reconstruct the reviewed overlays; never enroll a child dump as authority.
const merge = (target: Record<string, any>, patch: Record<string, any>) => {
  for (const [key, value] of Object.entries(patch)) {
    if (value && typeof value === 'object' && !Array.isArray(value) && !('__jsExpr' in value)) {
      target[key] ??= {}; merge(target[key], value)
    } else target[key] = value
  }
}
for (const patch of [...JSON.parse(DSH_SAFETY_PATCH), ...parse(DSH_MODEL_ROUTER_PATCH)]) {
  const row = expected.find(row => row.id === patch.id); assert.ok(row); merge(row,patch)
}
assert.deepEqual(parse(config),expected,'Composed config differs from reviewed static config + exact Host safety overlay')
validateDshComposedConfig(config)
const pin = {version:'0.2.0-rc.2' as const,sourceCommit:'639ed015397290b3745d163aafe02ffee4aa3f84',files,configDigest:sha(canonicalizeDshComposedConfig(config)),entryIds:reviewed.map(row=>row.id),pluginNames:[...new Set(reviewed.map(row=>row.name))]}
const policy = createPinnedDshDeployment({artifactDirectory:artifact,executable:join(artifact,'dsh'),pin})
await policy.verifyExecutable()
await policy.verifyDeployment({version:pin.version,executable:join(artifact,'dsh'),composedConfig:config,configDigest:pin.configDigest})
writeFileSync(new URL('safe-acp.yml',release),config)
writeFileSync(new URL('../src/release-darwin-arm64.ts',import.meta.url),"// Generated by scripts/review-official.ts after independent static-owner review.\nimport type { DshDeploymentPin } from './trusted-deployment.js'\nexport const DSH_DARWIN_ARM64_PIN: DshDeploymentPin = "+JSON.stringify(pin,null,2)+'\n')
const ledger = {artifact,sourceCommit:pin.sourceCommit,nodeVersion:execFileSync(join(artifact,'bin/node'),['--version'],{env,encoding:'utf8'}).trim(),files:Object.keys(files).length,artifactManifestDigest:sha(JSON.stringify(Object.fromEntries(Object.entries(files).sort(([a],[b])=>a<b?-1:a>b?1:0)))),defaultConfigDigest:sha(original),safeConfigDigest:pin.configDigest,entryIds:pin.entryIds,pluginNames:pin.pluginNames,checks:{version:0,acpHelp:0,dumpConfig:0,staticCompositionEqual:true,completeClosureVerified:true},modelCalled:false}
writeFileSync(new URL('ledger.json',release),JSON.stringify(ledger,null,2)+'\n')
console.log(JSON.stringify(ledger,null,2))
