import assert from 'node:assert/strict'
import test from 'node:test'
import { execFileSync } from 'node:child_process'
import { mkdtemp, mkdir, writeFile, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { auditRepositoryArchitecture } from './architecture-principles-gate.mjs'

test('candidate audit covers tracked and untracked sources without private Git history', async () => {
  const root = await mkdtemp(join(tmpdir(), 'architecture-candidate-'))
  try {
    execFileSync('git', ['init', '-q', root])
    await mkdir(join(root, 'packages/domains'), { recursive: true })
    await mkdir(join(root, 'src/main'), { recursive: true })
    await writeFile(join(root, 'src/main/tracked.ts'), 'export const tracked = true\n')
    execFileSync('git', ['-C', root, 'add', 'src/main/tracked.ts'])
    await writeFile(join(root, 'src/main/untracked.ts'), "import '@sciforge/domain-collaboration/main'\n")
    await assert.rejects(
      auditRepositoryArchitecture(root, { scope: 'candidate-tree' }),
      /src\/main\/untracked.ts: Host contains a domain-specific import/u
    )
    await writeFile(join(root, 'src/main/untracked.ts'), 'export const valid = true\n')
    const result = await auditRepositoryArchitecture(root, { scope: 'candidate-tree' })
    assert.equal(result.scope, 'candidate-tree')
    assert.equal(result.baseCommit, null)
    assert.equal(result.checkedProductionSourceCount, 2)
    assert.deepEqual(parseArchitecturePrinciplesOptions(['--candidate-tree']), { mode: 'candidate-tree' })
  } finally {
    await rm(root, { recursive: true, force: true })
  }
})

import {
  STAGE4_DEPLOYMENT,
  assertBundledStage4Contract,
  assertDomainPackageIdentity,
  auditChangedProductionSources,
  parseArchitecturePrinciplesOptions,
  safeArchiveLocator
} from './architecture-principles-gate.mjs'

test('formal gate requires the sealed Stage 4 artifact, receipt, and safe executable locator', () => {
  const options = parseArchitecturePrinciplesOptions([
    '--packed-artifact', 'dist/SciForge-0.1.0-mac-arm64.zip',
    '--artifact-receipt', 'dist/stage4-artifact-mac-arm64.json',
    '--packaged-executable-locator', 'SciForge.app/Contents/MacOS/SciForge'
  ])
  assert.equal(options.mode, 'formal')
  assert.equal(options.packagedExecutableLocator, 'SciForge.app/Contents/MacOS/SciForge')
  assert.throws(
    () => parseArchitecturePrinciplesOptions(['--packed-artifact', 'artifact.zip']),
    /--artifact-receipt is required/u
  )
  assert.throws(() => safeArchiveLocator('../SciForge.app'), /traversal/u)
  assert.throws(() => safeArchiveLocator('/Applications/SciForge.app'), /archive-relative/u)
})

test('changed production audit rejects Host feature maps, private imports, and compatibility shims', () => {
  assert.deepEqual(auditChangedProductionSources([{
    path: 'packages/domains/example/src/main.ts',
    source: "import type { Secret } from '@shared/private'\n"
  }, {
    path: 'src/main/example.ts',
    source: "import '@sciforge/domain-collaboration/main'\n"
  }, {
    path: 'packages/domains/opencontent-connector/src/main/settings.ts',
    source: 'const schema = legacyConnectionSettingsSchema\n'
  }]), [
    'packages/domains/example/src/main.ts: domain package imports a Host-private source path',
    'packages/domains/opencontent-connector/src/main/settings.ts: retired production marker legacyConnectionSettingsSchema',
    'src/main/example.ts: Host contains a domain-specific import or identifier'
  ])
})

test('generated composition and package-owned domain entrypoints satisfy the static contract', () => {
  assert.deepEqual(auditChangedProductionSources([{
    path: 'src/main/modules/installed-domain-main.ts',
    source: '// Generated by scripts/domain-packages.mjs. Do not edit.\n' +
      "import '@sciforge/domain-collaboration/main'\n"
  }, {
    path: 'packages/domains/example/src/main.ts',
    source: "import type { DomainMainHost } from '@sciforge/domain-sdk/host'\n"
  }]), [])
  assert.doesNotThrow(() => assertDomainPackageIdentity({
    name: '@sciforge/domain-example',
    version: '1.2.3'
  }, {
    packageName: '@sciforge/domain-example',
    module: { version: '1.2.3' },
    entrypoints: [
      { process: 'main', export: './main' },
      { process: 'renderer', export: './renderer' }
    ]
  }, 'packages/domains/example'))
  assert.throws(() => assertDomainPackageIdentity({
    name: '@sciforge/domain-example',
    version: '1.2.3'
  }, {
    packageName: '@sciforge/domain-example',
    module: { version: '1.2.4' },
    entrypoints: [{ process: 'main', export: './main' }]
  }, 'packages/domains/example'), /versions differ/u)
})

test('packaged bundle contains frozen OIDC/build identities and no source/mock fixtures', () => {
  const sourceCommit = 'a'.repeat(40)
  const bytes = Buffer.from([
    STAGE4_DEPLOYMENT.oidcAudience,
    STAGE4_DEPLOYMENT.oidcRedirectUri,
    'sciforgeStage4Build',
    'sciforge-stage4-acceptance',
    sourceCommit,
    'packaged-production-code'
  ].join('\n'))
  assert.doesNotThrow(() => assertBundledStage4Contract(
    bytes,
    '/private/source-root',
    sourceCommit
  ))
  assert.throws(
    () => assertBundledStage4Contract(Buffer.concat([
      bytes,
      Buffer.from('\nFakeCollaborationRepository')
    ]), '/private/source-root', sourceCommit),
    /forbidden source\/test identity/u
  )
  assert.throws(
    () => assertBundledStage4Contract(
      Buffer.from(STAGE4_DEPLOYMENT.oidcAudience),
      '/private/root',
      sourceCommit
    ),
    /missing required OIDC identity/u
  )
})


test('resolves domain-relative imports before classifying Host-private ownership', () => {
  assert.deepEqual(auditChangedProductionSources([{
    path: 'packages/domains/example/scripts/smoke.ts',
    source: "import { smoke } from '../src/main/smoke.js'\n"
  }]), [])
  for (const source of [
    "import { secret } from '../../../../src/main/private.js'",
    "import '@main/private'",
    "const secret = require('../../../../src/shared/private.cjs')"
  ]) {
    assert.equal(auditChangedProductionSources([{
      path: 'packages/domains/example/scripts/smoke.ts', source
    }]).length, 1)
  }
})

test('runtime MCP is generated composition only at the exact generated path and header', () => {
  const path = 'src/main/modules/installed-domain-runtime-mcp.ts'
  const body = "import '@sciforge/domain-computer-use/runtime-mcp'\n"
  const header = '// Generated by scripts/domain-packages.mjs. Do not edit.\n'
  assert.deepEqual(auditChangedProductionSources([{ path, source: header + body }]), [])
  assert.equal(auditChangedProductionSources([{ path, source: body }]).length, 1)
  assert.equal(auditChangedProductionSources([{ path: 'src/main/not-generated.ts', source: header + body }]).length, 1)
})

test('production cannot import test-only fixtures to escape architecture checks', () => {
  assert.deepEqual(auditChangedProductionSources([{
    path: 'src/main/extensions/__fixtures__/test-helpers.ts',
    source: "const packageName = '@sciforge/domain-test-extension'"
  }]), [])
  assert.match(auditChangedProductionSources([{
    path: 'src/main/extensions/loader.ts',
    source: "import { createSignedTestArtifact } from './__fixtures__/test-helpers'"
  }]).join('\n'), /production source imports test-only source/u)
})
