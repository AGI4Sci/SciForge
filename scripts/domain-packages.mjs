#!/usr/bin/env node

import { spawnSync } from 'node:child_process'
import { access, mkdir, readFile, readdir, realpath, writeFile } from 'node:fs/promises'
import path from 'node:path'
import process from 'node:process'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { tsImport } from 'tsx/esm/api'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const GENERATED_PATHS = Object.freeze({
  definitions: 'src/shared/installed-domain-packages.ts',
  main: 'src/main/modules/installed-domain-main.ts',
  renderer: 'src/renderer/src/domain-modules/installed-domain-renderer.ts',
  workspaceServer:
    'packages/workers/workspace-host/src/generated/installed-domain-workspace-server.ts'
})
const GENERATED_HEADER = '// Generated by scripts/domain-packages.mjs. Do not edit.\n'
const IMPLICIT_BUNDLED_RUNTIME_PATHS = new Set([
  'package.json',
  'sciforge.domain.json'
])

export async function discoverDomainPackages(
  root,
  options = {}
) {
  const domainsRoot = path.join(root, 'packages/domains')
  const entries = await readdir(domainsRoot, { withFileTypes: true })
  const packageDirectories = entries
    .filter((entry) => entry.isDirectory())
    .map((entry) => path.join(domainsRoot, entry.name))
    .sort()
  if (packageDirectories.length === 0) {
    throw new Error('No trusted domain packages were found in packages/domains/*.')
  }

  const parseDefinition = options.parseDefinition ?? await loadDefinitionParser(root)
  const discovered = []
  for (const packageRoot of packageDirectories) {
    const manifestPath = path.join(packageRoot, 'sciforge.domain.json')
    await requireFile(manifestPath, `Domain package ${path.basename(packageRoot)} is missing sciforge.domain.json.`)
    const rawManifest = parseJson(await readFile(manifestPath, 'utf8'), manifestPath)
    const definition = parseDefinition(rawManifest)
    validatePreviewContributionContracts(definition)
    const packageJsonPath = path.join(packageRoot, 'package.json')
    await requireFile(packageJsonPath, `Domain package ${definition.packageName} is missing package.json.`)
    const packageJson = parseJson(await readFile(packageJsonPath, 'utf8'), packageJsonPath)
    await validatePackageLayout({ packageRoot, definition, packageJson })
    discovered.push(Object.freeze({
      packageRoot,
      packageName: definition.packageName,
      definition,
      packageJson
    }))
  }

  discovered.sort((left, right) =>
    left.packageName < right.packageName ? -1 : left.packageName > right.packageName ? 1 : 0
  )
  const names = new Set()
  for (const candidate of discovered) {
    if (names.has(candidate.packageName)) {
      throw new Error(`Duplicate trusted domain package name: ${candidate.packageName}`)
    }
    names.add(candidate.packageName)
  }
  validateRuntimeDependencyGraph(discovered)
  return Object.freeze(discovered)
}

function validatePreviewContributionContracts(definition) {
  const contracts = definition.contributionContracts ?? {}
  const contributionIdsByProcess = new Map([
    ['main', []],
    ['renderer', []],
    ['workspace-server', []]
  ])
  for (const entrypoint of definition.entrypoints) {
    for (const contribution of entrypoint.contributions) {
      if (contribution.kind !== 'main.workspace-preview-plugin' &&
          contribution.kind !== 'renderer.workspace-preview-plugin' &&
          contribution.kind !== 'workspace-server.workspace-preview-plugin') continue
      if (!Object.hasOwn(contracts, contribution.id)) {
        throw new Error(
          `Domain package ${definition.packageName} preview ${contribution.id} requires one canonical contributionContracts entry.`
        )
      }
      contributionIdsByProcess.get(entrypoint.process).push(contribution.id)
    }
  }
  const nonEmptyProcessContributions = [...contributionIdsByProcess.entries()]
    .map(([processName, ids]) => [processName, ids.sort()])
    .filter(([, ids]) => ids.length > 0)
  if (nonEmptyProcessContributions.length === 0) return
  if (
    contributionIdsByProcess.get('renderer').length === 0 ||
    (
      contributionIdsByProcess.get('main').length === 0 &&
      contributionIdsByProcess.get('workspace-server').length === 0
    )
  ) {
    throw new Error(
      `Domain package ${definition.packageName} workspace preview contributions require a renderer and at least one backend process.`
    )
  }
  const canonicalIds = JSON.stringify(nonEmptyProcessContributions[0][1])
  if (nonEmptyProcessContributions.some(([, ids]) => JSON.stringify(ids) !== canonicalIds)) {
    throw new Error(
      `Domain package ${definition.packageName} must declare identical workspace preview contribution IDs in every declared preview process.`
    )
  }
}

export function renderGeneratedDomainPackageFiles(packages) {
  return Object.freeze({
    [GENERATED_PATHS.definitions]: renderDefinitions(packages),
    [GENERATED_PATHS.main]: renderMain(packages.filter(hasEntrypoint('main'))),
    [GENERATED_PATHS.renderer]: renderRenderer(packages.filter(hasEntrypoint('renderer'))),
    [GENERATED_PATHS.workspaceServer]: renderWorkspaceServer(
      packages.filter(hasEntrypoint('workspace-server'))
    )
  })
}

export async function generateDomainPackageFiles(root, { check = false } = {}) {
  const packages = await discoverDomainPackages(root)
  const generated = renderGeneratedDomainPackageFiles(packages)
  const stale = []
  for (const [relativePath, content] of Object.entries(generated)) {
    const target = path.join(root, relativePath)
    if (check) {
      const current = await readFile(target, 'utf8').catch(() => '')
      if (current !== content) stale.push(relativePath)
    } else {
      await mkdir(path.dirname(target), { recursive: true })
      await writeFile(target, content)
    }
  }
  if (stale.length > 0) {
    throw new Error(
      `Generated domain package composition is stale: ${stale.join(', ')}. ` +
      'Run npm run domain-packages:generate.'
    )
  }
  return packages
}

function renderDefinitions(packages) {
  const imports = packages.map((candidate, index) =>
    `import { domainPackageDefinition as domainPackageDefinition${index} } from '${candidate.packageName}/definition'`
  )
  const values = packages.map((_candidate, index) => `  domainPackageDefinition${index}`)
  return `${GENERATED_HEADER}import { defineInstalledDomainPackageSet } from '@sciforge/domain-sdk'\n${imports.join('\n')}\n\nexport const installedDomainPackages = defineInstalledDomainPackageSet([\n${values.join(',\n')}\n])\n`
}

function renderMain(packages) {
  const imports = packages.map((candidate, index) =>
    `import { createDomainMainEntry as createDomainMainEntry${index} } from '${candidate.packageName}/main'`
  )
  const values = packages.map((_candidate, index) => `      createDomainMainEntry${index}(domainHost)`)
  return `${GENERATED_HEADER}import type { DomainMainHost } from '@sciforge/domain-sdk/host'\nimport { defineInstalledMainDomainEntrySet } from '@sciforge/domain-sdk/main'\n${imports.join('\n')}${imports.length > 0 ? '\n' : ''}import type { z } from 'zod'\nimport { installedDomainPackages } from '../../shared/installed-domain-packages'\nimport { defineCapability, type DefineCapabilityOptions } from '../capabilities/registry'\n\nexport type InstalledMainDomainHost = Omit<DomainMainHost, 'defineCapability'>\n\nexport function createInstalledMainDomainEntries(host: InstalledMainDomainHost) {\n  const domainHost: DomainMainHost = {\n    ...host,\n    defineCapability: (options) => defineCapability(\n      options as DefineCapabilityOptions<z.ZodType, z.ZodType>\n    )\n  }\n  return defineInstalledMainDomainEntrySet<unknown>(\n    installedDomainPackages,\n    [\n${values.join(',\n')}\n    ]\n  ).entries\n}\n`
}

function renderRenderer(packages) {
  const imports = packages.map((candidate, index) =>
    `import { createDomainRendererEntry as createDomainRendererEntry${index} } from '${candidate.packageName}/renderer'`
  )
  const values = packages.map((_candidate, index) => `    createDomainRendererEntry${index}(domainHost)`)
  return `${GENERATED_HEADER}import type { DomainRendererContribution, DomainRendererHost } from '@sciforge/domain-sdk/host'\nimport { defineInstalledRendererDomainEntrySet } from '@sciforge/domain-sdk/renderer'\n${imports.join('\n')}${imports.length > 0 ? '\n' : ''}import { installedDomainPackages } from '@shared/installed-domain-packages'\nimport type { VisibleContextComponentSnapshot } from '@shared/visible-context'\nimport { rendererCapabilityClient } from '../lib/capability-client'\nimport { openSafeExternalUrl } from '../lib/open-external'\nimport {\n  inspectRegisteredVisibleContextTargetAt,\n  inspectRegisteredVisibleContextTextSelection,\n  registerVisibleContextComponent,\n  registerVisibleContextVisualTarget\n} from '../lib/visible-context'\nimport { domainRendererNavigationHost } from './domain-renderer-navigation'\n\nlet rendererContributions: readonly DomainRendererContribution[] = []\nconst domainHost: DomainRendererHost = {\n  capabilityInvoker: rendererCapabilityClient,\n  contributions: {\n    list: (kind) => rendererContributions.filter((contribution) => contribution.kind === kind)\n  },\n  openExternal: async (url) => {\n    await openSafeExternalUrl(url)\n  },\n  workspace: {\n    pickFile: (request) => window.sciforge.pickFile(request),\n    openRemoteSession: async (input) => {\n      await window.sciforge.remoteWorkspace.attach(input)\n    }\n  },\n  ...domainRendererNavigationHost,\n  visibleContext: {\n    registerComponent: (component) => registerVisibleContextComponent(\n      component as VisibleContextComponentSnapshot\n    ),\n    registerVisualTarget: ({ element, ...input }) => registerVisibleContextVisualTarget({\n      ...input,\n      ...(element ? { element: element as () => Element | null } : {})\n    }),\n    inspectRegisteredTargetAt: inspectRegisteredVisibleContextTargetAt,\n    inspectRegisteredTextSelection: inspectRegisteredVisibleContextTextSelection\n  }\n}\n\nexport const installedRendererDomainEntrySet = defineInstalledRendererDomainEntrySet<unknown>(\n  installedDomainPackages,\n  [\n${values.join(',\n')}\n  ]\n)\nrendererContributions = Object.freeze(installedRendererDomainEntrySet.contributions.map((contribution) => Object.freeze({\n  id: contribution.declaration.id,\n  kind: contribution.declaration.kind,\n  packageName: contribution.packageName,\n  owner: contribution.owner,\n  ...(contribution.contract === undefined ? {} : { contract: contribution.contract }),\n  value: contribution.value\n})))\n`
}

function renderWorkspaceServer(packages) {
  const definitionImports = packages.map((candidate, index) =>
    `import { domainPackageDefinition as domainPackageDefinition${index} } from '${candidate.packageName}/definition'`
  )
  const entryImports = packages.map((candidate, index) =>
    `import { createDomainWorkspaceServerEntry as createDomainWorkspaceServerEntry${index} } from '${candidate.packageName}/workspace-server'`
  )
  const definitions = packages.map((_candidate, index) => `  domainPackageDefinition${index}`)
  const values = packages.map(
    (_candidate, index) => `      createDomainWorkspaceServerEntry${index}(host)`
  )
  return `${GENERATED_HEADER}import { defineInstalledDomainPackageSet } from '@sciforge/domain-sdk'\nimport type { DomainWorkspaceServerHost } from '@sciforge/domain-sdk/workspace-server'\nimport { defineInstalledWorkspaceServerDomainEntrySet } from '@sciforge/domain-sdk/workspace-server'\n${definitionImports.join('\n')}${definitionImports.length > 0 ? '\n' : ''}${entryImports.join('\n')}${entryImports.length > 0 ? '\n' : ''}\nconst installedWorkspaceServerDomainPackages = defineInstalledDomainPackageSet([\n${definitions.join(',\n')}\n])\n\nexport function createInstalledWorkspaceServerDomainEntries(host: DomainWorkspaceServerHost) {\n  return defineInstalledWorkspaceServerDomainEntrySet<unknown>(\n    installedWorkspaceServerDomainPackages,\n    [\n${values.join(',\n')}\n    ]\n  ).entries\n}\n`
}

function hasEntrypoint(processName) {
  return (candidate) => candidate.definition.entrypoints.some((entrypoint) =>
    entrypoint.process === processName
  )
}

async function validatePackageLayout({ packageRoot, definition, packageJson }) {
  if (packageJson.name !== definition.packageName) {
    throw new Error(
      `${relative(packageRoot)}/package.json name must equal manifest packageName ${definition.packageName}.`
    )
  }
  if (!isRecord(packageJson.exports)) {
    throw new Error(`Domain package ${definition.packageName} must declare package.json exports.`)
  }
  if (Object.hasOwn(packageJson.exports, '.')) {
    throw new Error(`Domain package ${definition.packageName} must not expose a process-ambiguous root export.`)
  }
  await validateNamedExport(
    packageRoot,
    definition.packageName,
    packageJson.exports,
    './definition',
    'domainPackageDefinition'
  )
  for (const processName of ['main', 'renderer', 'workspace-server']) {
    const entrypoint = definition.entrypoints.find((candidate) => candidate.process === processName)
    const exportName = `./${processName}`
    if (Boolean(entrypoint) !== Object.hasOwn(packageJson.exports, exportName)) {
      throw new Error(
        `Domain package ${definition.packageName} manifest and package.json disagree on ${exportName}.`
      )
    }
    if (entrypoint) {
      if (entrypoint.export !== exportName) {
        throw new Error(`Domain package ${definition.packageName} must use ${exportName} for ${processName}.`)
      }
      await validateNamedExport(
        packageRoot,
        definition.packageName,
        packageJson.exports,
        exportName,
        processName === 'main'
          ? 'createDomainMainEntry'
          : processName === 'renderer'
            ? 'createDomainRendererEntry'
            : 'createDomainWorkspaceServerEntry'
      )
    }
  }
  if (!isRecord(packageJson.scripts) || typeof packageJson.scripts.test !== 'string' ||
    typeof packageJson.scripts.typecheck !== 'string') {
    throw new Error(`Domain package ${definition.packageName} must provide test and typecheck scripts.`)
  }
  await validatePackagingLayout({ packageRoot, definition })
}

async function validatePackagingLayout({ packageRoot, definition }) {
  const packaging = definition.packaging
  if (packaging === undefined) return
  if (!isRecord(packaging) || typeof packaging.bundled !== 'boolean') {
    throw new Error(`Domain package ${definition.packageName} packaging.bundled must be a boolean.`)
  }
  const runtime = packaging.runtime
  if (runtime === undefined) return
  if (!isRecord(runtime)) {
    throw new Error(`Domain package ${definition.packageName} packaging.runtime must be an object.`)
  }
  const requiredPaths = runtime.requiredPaths ?? []
  const dependencies = runtime.dependencies ?? []
  validateUniqueStringArray(
    requiredPaths,
    `Domain package ${definition.packageName} runtime required paths`
  )
  validateUniqueStringArray(
    dependencies,
    `Domain package ${definition.packageName} runtime dependencies`
  )
  if (!packaging.bundled && (requiredPaths.length > 0 || dependencies.length > 0)) {
    throw new Error(
      `Non-bundled domain package ${definition.packageName} cannot declare packaged runtime requirements.`
    )
  }
  if (dependencies.includes(definition.packageName)) {
    throw new Error(`Domain package ${definition.packageName} cannot depend on itself at runtime.`)
  }

  const canonicalPackageRoot = await realpath(packageRoot)
  for (const requiredPath of requiredPaths) {
    validatePackageRelativePath(requiredPath, definition.packageName)
    const resolved = path.resolve(packageRoot, ...requiredPath.split('/'))
    await requireFile(
      resolved,
      `Bundled domain package ${definition.packageName} is missing runtime path ${requiredPath}.`
    )
    const canonicalRequiredPath = await realpath(resolved)
    if (!isWithinDirectory(canonicalPackageRoot, canonicalRequiredPath)) {
      throw new Error(
        `Bundled domain package ${definition.packageName} runtime path ${requiredPath} escapes its package root.`
      )
    }
  }
}

function validateRuntimeDependencyGraph(packages) {
  const packageByName = new Map(packages.map((candidate) => [
    candidate.packageName,
    candidate
  ]))
  const bundled = packages.filter((candidate) => candidate.definition.packaging?.bundled)
  for (const candidate of bundled) {
    for (const dependency of candidate.definition.packaging?.runtime?.dependencies ?? []) {
      const resolved = packageByName.get(dependency)
      if (!resolved) {
        throw new Error(
          `Bundled domain package ${candidate.packageName} depends on uninstalled domain ${dependency}.`
        )
      }
      if (!resolved.definition.packaging?.bundled) {
        throw new Error(
          `Bundled domain package ${candidate.packageName} depends on non-bundled domain ${dependency}.`
        )
      }
    }
  }

  const visited = new Set()
  const visiting = new Set()
  const stack = []
  const visit = (candidate) => {
    if (visited.has(candidate.packageName)) return
    if (visiting.has(candidate.packageName)) {
      const cycleStart = stack.indexOf(candidate.packageName)
      const cycle = [...stack.slice(cycleStart), candidate.packageName]
      throw new Error(`Cyclic bundled domain runtime dependency: ${cycle.join(' -> ')}`)
    }
    visiting.add(candidate.packageName)
    stack.push(candidate.packageName)
    for (const dependency of candidate.definition.packaging?.runtime?.dependencies ?? []) {
      visit(packageByName.get(dependency))
    }
    stack.pop()
    visiting.delete(candidate.packageName)
    visited.add(candidate.packageName)
  }
  for (const candidate of bundled) visit(candidate)
}

function validateUniqueStringArray(value, label) {
  if (!Array.isArray(value) || value.some((entry) => typeof entry !== 'string')) {
    throw new Error(`${label} must be an array of strings.`)
  }
  if (new Set(value).size !== value.length) {
    throw new Error(`${label} must not contain duplicates.`)
  }
}

function validatePackageRelativePath(relativePath, packageName) {
  if (
    relativePath.length === 0 ||
    relativePath !== relativePath.trim() ||
    relativePath.startsWith('/') ||
    /^[A-Za-z]:\//.test(relativePath) ||
    relativePath.includes('\\') ||
    relativePath.includes('\0') ||
    relativePath.split('/').some((segment) =>
      segment === '' || segment === '.' || segment === '..'
    )
  ) {
    throw new Error(
      `Bundled domain package ${packageName} runtime path must be package-relative: ${relativePath}`
    )
  }
  if (IMPLICIT_BUNDLED_RUNTIME_PATHS.has(relativePath)) {
    throw new Error(
      `Bundled domain package ${packageName} must not repeat implicit runtime path ${relativePath}.`
    )
  }
}

function isWithinDirectory(directory, candidate) {
  return candidate === directory || candidate.startsWith(`${directory}${path.sep}`)
}

function validateNamedExport(packageRoot, packageName, exportsMap, subpath, symbol) {
  const target = exportsMap[subpath]
  if (typeof target !== 'string' || !target.startsWith('./')) {
    throw new Error(`Domain package ${packageName} must map ${subpath} to a local source file.`)
  }
  const sourcePath = path.resolve(packageRoot, target)
  if (!sourcePath.startsWith(`${packageRoot}${path.sep}`)) {
    throw new Error(`Domain package ${packageName} export ${subpath} escapes its package root.`)
  }
  return requireSourceExport(sourcePath, symbol, new Set()).catch((error) => {
    throw new Error(`Domain package ${packageName} ${subpath} must export ${symbol}: ${error.message}`)
  })
}

async function requireSourceExport(sourcePath, symbol, visited) {
  const resolved = await resolveSourcePath(sourcePath)
  if (visited.has(resolved)) throw new Error('cyclic re-export')
  visited.add(resolved)
  const source = await readFile(resolved, 'utf8')
  const direct = new RegExp(`export\\s+(?:async\\s+)?(?:const|function|class)\\s+${symbol}\\b`)
  const named = new RegExp(`export\\s*\\{[^}]*\\b${symbol}\\b[^}]*\\}`)
  if (direct.test(source) || named.test(source)) return

  const reexports = [...source.matchAll(/export\s+\*\s+from\s+['"]([^'"]+)['"]/g)]
  for (const match of reexports) {
    if (!match[1]?.startsWith('.')) continue
    try {
      await requireSourceExport(path.resolve(path.dirname(resolved), match[1]), symbol, new Set(visited))
      return
    } catch {
      // Keep searching other explicit local re-exports.
    }
  }
  throw new Error(`symbol was not found from ${relative(resolved)}`)
}

async function resolveSourcePath(candidate) {
  for (const pathCandidate of [
    candidate,
    `${candidate}.ts`,
    `${candidate}.tsx`,
    path.join(candidate, 'index.ts'),
    path.join(candidate, 'index.tsx')
  ]) {
    try {
      await access(pathCandidate)
      return pathCandidate
    } catch {
      // Continue through supported TypeScript source forms.
    }
  }
  throw new Error(`source file not found: ${relative(candidate)}`)
}

async function loadDefinitionParser(root) {
  const contractPath = path.join(root, 'packages/domain-sdk/src/contract.ts')
  const contract = await tsImport(pathToFileURL(contractPath).href, { parentURL: import.meta.url })
  if (typeof contract.defineTrustedDomainPackage !== 'function') {
    throw new Error('Domain SDK does not export defineTrustedDomainPackage.')
  }
  return contract.defineTrustedDomainPackage
}

async function requireFile(filePath, message) {
  try {
    await access(filePath)
  } catch {
    throw new Error(message)
  }
}

function parseJson(source, filePath) {
  try {
    return JSON.parse(source)
  } catch (error) {
    throw new Error(`Invalid JSON in ${relative(filePath)}: ${error.message}`)
  }
}

function isRecord(value) {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
}

function relative(filePath) {
  return path.relative(ROOT, filePath).split(path.sep).join('/')
}

function runPackageScript(packages, scriptName) {
  for (const candidate of packages) {
    const result = spawnSync(
      process.platform === 'win32' ? 'npm.cmd' : 'npm',
      ['--workspace', candidate.packageName, 'run', scriptName],
      { cwd: ROOT, stdio: 'inherit' }
    )
    if (result.error) throw result.error
    if (result.status !== 0) {
      throw new Error(`${candidate.packageName} ${scriptName} failed with exit code ${result.status}.`)
    }
  }
}

async function main(argv) {
  const command = argv[0] ?? '--check'
  if (command === '--generate') {
    const packages = await generateDomainPackageFiles(ROOT)
    console.log(`Generated trusted domain composition for ${packages.length} package(s).`)
    return
  }
  if (command === '--check') {
    const packages = await generateDomainPackageFiles(ROOT, { check: true })
    console.log(`Trusted domain composition is fresh for ${packages.length} package(s).`)
    return
  }
  if (command === '--run' && (argv[1] === 'test' || argv[1] === 'typecheck')) {
    const packages = await generateDomainPackageFiles(ROOT, { check: true })
    runPackageScript(packages, argv[1])
    return
  }
  throw new Error('Usage: domain-packages.mjs --generate | --check | --run test | --run typecheck')
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2)).catch((error) => {
    console.error(error instanceof Error ? error.message : String(error))
    process.exitCode = 1
  })
}
