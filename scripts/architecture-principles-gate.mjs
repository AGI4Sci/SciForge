export function parseArchitecturePrinciplesOptions(argv) {
  if (argv.length === 1 && argv[0] === '--changed-path-only') {
    return Object.freeze({ mode: 'changed-path-only' })
  }
  const allowed = new Set([
    '--packed-artifact',
    '--artifact-receipt',
    '--packaged-executable-locator',
    '--private-domain-package'
  ])
  const required = new Set([
    '--packed-artifact',
    '--artifact-receipt',
    '--packaged-executable-locator'
  ])
  const values = new Map()
  const privateDomainPackagePaths = []
  for (let index = 0; index < argv.length; index += 1) {
    const flag = argv[index]
    if (!allowed.has(flag)) throw new Error(`Unknown architecture gate option: ${flag}`)
    if (values.has(flag)) throw new Error(`Duplicate architecture gate option: ${flag}`)
    const value = argv[index + 1]?.trim()
    if (!value || value.startsWith('--')) throw new Error(`${flag} requires a value.`)
    if (flag === '--private-domain-package') {
      if (!isAbsolute(value)) {
        throw new Error('Architecture gate private domain package path must be absolute.')
      }
      privateDomainPackagePaths.push(value)
      index += 1
      continue
    }
    if (values.has(flag)) throw new Error(`Duplicate architecture gate option: ${flag}`)
    values.set(flag, value)
    index += 1
  }
  for (const flag of required) {
    if (!values.has(flag)) throw new Error(`${flag} is required for the formal gate.`)
  }
  if (privateDomainPackagePaths.length === 0) {
    throw new Error('--private-domain-package is required for the formal gate.')
  }
  return Object.freeze({
    mode: 'formal',
    artifactReceipt: resolve(values.get('--artifact-receipt')),
    packagedArtifact: resolve(values.get('--packed-artifact')),
    privateDomainPackagePaths: Object.freeze(privateDomainPackagePaths),
    packagedExecutableLocator: safeArchiveLocator(
      values.get('--packaged-executable-locator')
    )
  })
}

export function safeArchiveLocator(value) {
  if (typeof value !== 'string' || !value || isAbsolute(value) || value.includes('\\')) {
    throw new Error('Packaged executable locator must be a safe archive-relative POSIX path.')
  }
  const segments = value.split('/')
  if (segments.some((segment) => !segment || segment === '.' || segment === '..')) {
    throw new Error('Packaged executable locator must not contain empty or traversal segments.')
  }
  return segments.join('/')
}

export function auditChangedProductionSources(entries) {
  const findings = []
  for (const entry of entries) {
    const path = entry.path.replaceAll('\\', '/')
    const source = entry.source
    if (!isProductionSourcePath(path)) continue
    if (isGeneratedComposition(path, source)) continue

    if (path.startsWith('packages/domains/') && hasHostPrivateImport(source)) {
      findings.push(`${path}: domain package imports a Host-private source path`)
    }
    if (isHostProductionPath(path) && hasDirectDomainReference(source)) {
      findings.push(`${path}: Host contains a domain-specific import or identifier`)
    }
    for (const marker of RETIRED_PRODUCTION_MARKERS) {
      if (source.includes(marker)) {
        findings.push(`${path}: retired production marker ${marker}`)
      }
    }
  }
  return Object.freeze(findings.sort())
}

export function assertDomainPackageIdentity(packageJson, manifest, path) {
  if (!packageJson || !manifest || packageJson.name !== manifest.packageName) {
    throw new Error(`${path}: package and domain manifest names differ.`)
  }
  if (packageJson.version !== manifest.module?.version) {
    throw new Error(`${path}: backend/UI package and module versions differ.`)
  }
  if (!Array.isArray(manifest.entrypoints) || manifest.entrypoints.length === 0) {
    throw new Error(`${path}: domain package has no explicit process entrypoint.`)
  }
  const processes = new Set()
  for (const entrypoint of manifest.entrypoints) {
    if (!entrypoint || !['main', 'renderer', 'workspace-server'].includes(entrypoint.process) ||
      typeof entrypoint.export !== 'string' || !entrypoint.export.startsWith('./')) {
      throw new Error(`${path}: domain package entrypoint is invalid.`)
    }
    if (processes.has(entrypoint.process)) {
      throw new Error(`${path}: domain package has duplicate ${entrypoint.process} entrypoints.`)
    }
    processes.add(entrypoint.process)
  }
}

export function assertBundledStage4Contract(
  contractSurfaces,
  repositoryRoot = REPOSITORY_ROOT,
  sourceCommit,
  privateComposition
) {
  const surfaces = Buffer.isBuffer(contractSurfaces)
    ? [contractSurfaces]
    : contractSurfaces
  if (!Array.isArray(surfaces) || surfaces.length === 0 ||
    surfaces.some((bytes) => !Buffer.isBuffer(bytes) || bytes.byteLength === 0)) {
    throw new Error('Packaged application contract bytes are empty or unavailable.')
  }
  const includes = (identity) => surfaces.some((bytes) => bytes.includes(Buffer.from(identity)))
  const requiredIdentities = [
    ...REQUIRED_BUNDLED_IDENTITIES,
    ...(sourceCommit ? ['sciforgeStage4Build', 'sciforge-stage4-acceptance', sourceCommit] : [])
  ]
  for (const identity of requiredIdentities) {
    if (!includes(identity)) {
      throw new Error(`Packaged application is missing required OIDC identity: ${identity}`)
    }
  }
  for (const identity of [
    ...(privateComposition?.privateDomainPackages ?? []).map((entry) => entry.packageName)
  ]) {
    if (!includes(identity)) {
      throw new Error(`Packaged application is missing private composition identity: ${identity}`)
    }
  }
  for (const identity of [...FORBIDDEN_BUNDLED_IDENTITIES, resolve(repositoryRoot)]) {
    if (includes(identity)) {
      throw new Error(`Packaged application contains a forbidden source/test identity: ${identity}`)
    }
  }
}

export async function auditRepositoryArchitecture(repositoryRoot = REPOSITORY_ROOT) {
  const root = resolve(repositoryRoot)
  await assertBaseIsAncestor(root)
  const changedPaths = await gitLines(root, [
    'diff',
    '--name-only',
    '--diff-filter=ACMRTUXB',
    `${ARCHITECTURE_BASE_COMMIT}...HEAD`
  ])
  const entries = []
  for (const path of changedPaths) {
    if (!isProductionSourcePath(path)) continue
    entries.push({ path, source: await readFile(join(root, path), 'utf8') })
  }
  const findings = [...auditChangedProductionSources(entries)]
  const retiredPackagePath = join(root, 'packages', 'collaboration-identity')
  if (await pathExists(retiredPackagePath)) {
    findings.push('packages/collaboration-identity: retired credential package still exists')
  }

  const domainsRoot = join(root, 'packages', 'domains')
  let domainPackageCount = 0
  for (const directory of await readdir(domainsRoot, { withFileTypes: true })) {
    if (!directory.isDirectory()) continue
    const packageRoot = join(domainsRoot, directory.name)
    const packagePath = `packages/domains/${directory.name}`
    const packageJson = JSON.parse(await readFile(join(packageRoot, 'package.json'), 'utf8'))
    const manifest = JSON.parse(await readFile(join(packageRoot, 'sciforge.domain.json'), 'utf8'))
    try {
      assertDomainPackageIdentity(packageJson, manifest, packagePath)
      domainPackageCount += 1
    } catch (error) {
      findings.push(error instanceof Error ? error.message : String(error))
    }
  }
  if (findings.length > 0) {
    throw new Error(`Changed-path architecture audit failed:\n${findings.sort().join('\n')}`)
  }
  return Object.freeze({
    baseCommit: ARCHITECTURE_BASE_COMMIT,
    changedPathCount: changedPaths.length,
    checkedProductionSourceCount: entries.length,
    domainPackageCount,
    findings: Object.freeze([])
  })
}

async function runFormalGate(options) {
  const startedAt = new Date().toISOString()
  const opening = readExactSourceState(REPOSITORY_ROOT, true)
  if (opening.branch !== STAGE4_BRANCH) {
    throw new Error(`Formal gate must run on ${STAGE4_BRANCH}; found ${opening.branch}.`)
  }

  const architecture = await auditRepositoryArchitecture(REPOSITORY_ROOT)
  await runCommand('npm', ['run', 'architecture-principles:test'])
  await runCommand('npm', ['run', 'capability:check'])
  await runCommand('node', ['scripts/collaboration-secret-audit.mjs'])
  await runCommand('npm', ['run', 'build'])
  await runSmoke('scripts/electron-domain-smoke.mjs')

  const artifact = await verifyAndExtractArtifact(options, opening)
  try {
    await runSmoke('scripts/electron-domain-packaged-smoke.mjs', [
      '--executable', artifact.executablePath
    ])
    artifact.receiptHandle.assertUnchanged()
    const closing = readExactSourceState(REPOSITORY_ROOT, true)
    if (JSON.stringify(closing) !== JSON.stringify(opening)) {
      throw new Error('Git source identity changed while the formal architecture gate was running.')
    }
    const receipt = Object.freeze({
      contractVersion: 1,
      kind: 'sciforge-architecture-principles-gate',
      status: 'passed',
      source: opening,
      baselineCommit: ARCHITECTURE_BASE_COMMIT,
      changedPath: architecture,
      artifact: Object.freeze({
        path: options.packagedArtifact,
        receiptPath: options.artifactReceipt,
        fileName: artifact.file.fileName,
        size: artifact.file.size,
        sha256: artifact.file.sha256,
        platform: artifact.file.platform,
        architecture: artifact.file.architecture,
        executableLocator: options.packagedExecutableLocator,
        executableArchitectures: artifact.executableArchitectures,
        copiedFromReceiptHeldBytes: true,
        sourceIndependentWorkingDirectory: dirname(artifact.executablePath)
      }),
      deployment: STAGE4_DEPLOYMENT,
      build: artifact.receipt.build,
      privateComposition: artifact.receipt.composition,
      gates: Object.freeze({
        changedPathArchitecture: 'passed',
        generatedComposition: 'passed',
        capabilityGovernance: 'passed',
        secretBoundary: 'passed',
        privateAcceptanceComposition: 'passed',
        sourceProductionComposition: 'passed',
        packagedProductionComposition: 'passed',
        unchangedCommitAndWorkspace: 'passed'
      }),
      startedAt,
      completedAt: new Date().toISOString()
    })
    const outputPath = join(dirname(options.artifactReceipt), 'architecture-principles-gate.json')
    await writeFile(outputPath, `${JSON.stringify(receipt, null, 2)}\n`, {
      encoding: 'utf8',
      flag: 'w',
      mode: 0o644
    })
    process.stdout.write(`${JSON.stringify({ ...receipt, outputPath }, null, 2)}\n`)
  } finally {
    artifact.receiptHandle.close()
    await rm(artifact.temporaryDirectory, { recursive: true, force: true })
  }
}

async function verifyAndExtractArtifact(options, source) {
  if (dirname(options.packagedArtifact) !== dirname(options.artifactReceipt)) {
    throw new Error('Packed artifact and Stage 4 receipt must share one directory.')
  }
  const receiptHandle = verifyStage4ArtifactReceipt({
    artifactPath: options.packagedArtifact,
    receiptPath: options.artifactReceipt,
    source
  })
  const file = receiptHandle.artifact
  const fileName = file.fileName
  if (file.platform !== 'mac' || file.architecture !== process.arch ||
    !fileName.endsWith(`-mac-${process.arch}.zip`)) {
    receiptHandle.close()
    throw new Error(`Packed artifact does not target the current ${process.arch} architecture.`)
  }

  const temporaryDirectory = await mkdtemp(join(tmpdir(), 'sciforge-stage4-artifact-'))
  try {
    const heldArchive = join(temporaryDirectory, fileName)
    const extractionRoot = join(temporaryDirectory, 'extracted')
    await pipeline(
      receiptHandle.openReadStream(fileName),
      createWriteStream(heldArchive, { flags: 'wx', mode: 0o600 })
    )
    await runCommand('/usr/bin/ditto', ['-x', '-k', heldArchive, extractionRoot])
    const executablePath = await resolveArchiveFile(
      extractionRoot,
      options.packagedExecutableLocator
    )
    const { stdout: fileDescription } = await execFile('/usr/bin/file', ['-b', executablePath], {
      cwd: temporaryDirectory,
      encoding: 'utf8'
    })
    if (!new RegExp(`(?:^|\\W)${process.arch}(?:\\W|$)`, 'u').test(fileDescription)) {
      throw new Error(`Packaged executable architecture mismatch: ${fileDescription.trim()}`)
    }
    const appBundle = options.packagedExecutableLocator.split('/').findIndex((part) => (
      part.endsWith('.app')
    ))
    if (appBundle < 0) throw new Error('macOS executable locator contains no .app bundle.')
    const appAsar = join(
      extractionRoot,
      ...options.packagedExecutableLocator.split('/').slice(0, appBundle + 1),
      'Contents',
      'Resources',
      'app.asar'
    )
    const resourcesRoot = join(
      extractionRoot,
      ...options.packagedExecutableLocator.split('/').slice(0, appBundle + 1),
      'Contents',
      'Resources'
    )
    const contractSurfaces = [await readRegularFile(appAsar)]
    const unpackedMain = join(
      resourcesRoot,
      'app.asar.unpacked',
      'out',
      'main',
      'index.js'
    )
    if (await pathExists(unpackedMain)) {
      contractSurfaces.push(await readRegularFile(unpackedMain))
    }
    assertBundledStage4Contract(
      contractSurfaces,
      REPOSITORY_ROOT,
      source.commit,
      receiptHandle.receipt.composition
    )
    const internalRuntimeComposition = createInternalRuntimeComposition(REPOSITORY_ROOT)
    const deploymentConfigurationComposition =
      createDomainPackageDeploymentConfigurationComposition(REPOSITORY_ROOT)
    verifyPackagedInternalRuntimes(resourcesRoot, internalRuntimeComposition)
    verifyPackagedDomainDeploymentConfigurations(
      resourcesRoot,
      deploymentConfigurationComposition
    )
    const privateComposition = await verifyStage4PrivateDomainPackageInputs({
      repositoryRoot: REPOSITORY_ROOT,
      privateDomainPackagePaths: options.privateDomainPackagePaths,
      now: new Date()
    })
    const freshComposition = summarizePrivateComposition({
      deploymentConfigurationComposition,
      internalRuntimeComposition,
      privateComposition
    })
    if (JSON.stringify(freshComposition) !== JSON.stringify(receiptHandle.receipt.composition)) {
      throw new Error('Stage 4 receipt private composition differs from the gate checkout.')
    }
    receiptHandle.assertUnchanged()
    return Object.freeze({
      executableArchitectures: Object.freeze([process.arch]),
      executablePath,
      file,
      receipt: receiptHandle.receipt,
      receiptHandle,
      temporaryDirectory
    })
  } catch (error) {
    receiptHandle.close()
    await rm(temporaryDirectory, { recursive: true, force: true })
    throw error
  }
}

async function resolveArchiveFile(extractionRoot, locator) {
  const root = await realpath(extractionRoot)
  let current = root
  for (const segment of safeArchiveLocator(locator).split('/')) {
    current = join(current, segment)
    const entry = await lstat(current)
    if (entry.isSymbolicLink()) throw new Error(`Archive locator contains a symlink: ${segment}`)
  }
  const canonical = await realpath(current)
  const relation = relative(root, canonical)
  if (!relation || relation === '..' || relation.startsWith(`..${sep}`) || isAbsolute(relation)) {
    throw new Error('Packaged executable locator escapes the extracted archive.')
  }
  const executable = await lstat(canonical)
  if (!executable.isFile()) throw new Error('Packaged executable locator is not a regular file.')
  await access(canonical)
  return canonical
}

async function readRegularFile(path) {
  const entry = await lstat(path)
  if (!entry.isFile() || entry.isSymbolicLink()) {
    throw new Error(`Expected a regular packaged file: ${path}`)
  }
  return readFile(path)
}

async function runSmoke(script, leadingArguments = []) {
  await runCommand('node', [
    script,
    ...leadingArguments,
    '--expected-cloud-origin', STAGE4_DEPLOYMENT.cloudOrigin,
    '--expected-oidc-issuer', STAGE4_DEPLOYMENT.oidcIssuer,
    '--timeout-ms', '180000'
  ])
}

async function runCommand(command, args) {
  await new Promise((resolvePromise, reject) => {
    const child = spawn(command, args, {
      cwd: REPOSITORY_ROOT,
      env: process.env,
      stdio: 'inherit'
    })
    child.once('error', reject)
    child.once('exit', (code, signal) => {
      if (code === 0 && signal === null) resolvePromise()
      else reject(new Error(
        `${command} ${args.join(' ')} exited with code ${code ?? 'null'} and signal ${signal ?? 'none'}.`
      ))
    })
  })
}

async function assertBaseIsAncestor(root) {
  try {
    await execFile('git', ['merge-base', '--is-ancestor', ARCHITECTURE_BASE_COMMIT, 'HEAD'], {
      cwd: root
    })
  } catch {
    throw new Error(`Architecture baseline ${ARCHITECTURE_BASE_COMMIT} is not an ancestor of HEAD.`)
  }
}

async function gitLines(root, args) {
  const value = await gitText(root, args)
  return value ? value.split('\n').filter(Boolean) : []
}

async function gitText(root, args) {
  const { stdout } = await execFile('git', args, { cwd: root, encoding: 'utf8' })
  return stdout.trim()
}

function isProductionSourcePath(path) {
  return /^(?:packages|src)\//u.test(path) &&
    /\.(?:cjs|js|mjs|ts|tsx)$/u.test(path) &&
    !/\.(?:integration\.)?test\.[^.]+$/u.test(path) &&
    !path.includes('/test-fixtures/') &&
    !path.includes('/__fixtures__/')
}

function isHostProductionPath(path) {
  return /^(?:src\/main|src\/renderer|src\/shared)\//u.test(path)
}

function isGeneratedComposition(path, source) {
  return source.startsWith(GENERATED_HEADER) && [
    'src/shared/installed-domain-packages.ts',
    'src/main/modules/installed-domain-main.ts',
    'src/main/modules/installed-main-source-packages.ts',
    'src/renderer/src/domain-modules/installed-domain-renderer.ts'
  ].includes(path)
}

function hasHostPrivateImport(source) {
  return /(?:from\s*|import\s*\()\s*['"][^'"]*(?:@shared|@renderer|@main|\/src\/(?:main|renderer|shared))(?:\/|['"])/u
    .test(source)
}

function hasDirectDomainReference(source) {
  return /@sciforge\/domain-(?!sdk(?:\/|['"]))[a-z0-9-]+|sciforge\.(?:collaboration|identity-access|project-coordinator|content-space|opencontent)/u
    .test(source)
}

async function pathExists(path) {
  try {
    await access(path)
    return true
  } catch {
    return false
  }
}

async function main(argv) {
  const options = parseArchitecturePrinciplesOptions(argv)
  if (options.mode === 'changed-path-only') {
    const report = await auditRepositoryArchitecture(REPOSITORY_ROOT)
    process.stdout.write(`${JSON.stringify({ status: 'passed', ...report }, null, 2)}\n`)
    return
  }
  await runFormalGate(options)
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2)).catch((error) => {
    process.stderr.write(`[architecture-principles] ${error instanceof Error ? error.message : String(error)}\n`)
    process.exitCode = 1
  })
}
