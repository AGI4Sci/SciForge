import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { createServer } from 'vite'
import react from '@vitejs/plugin-react'
import { chromium } from 'playwright-core'
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..'),out=path.resolve(process.argv[2])
await mkdir(out,{recursive:false})
const server=await createServer({root,configFile:false,cacheDir:path.join(out,'vite-cache'),plugins:[react()],server:{host:'127.0.0.1',port:0,hmr:false,watch:null,fs:{allow:[root,path.resolve(root,'node_modules')]}},logLevel:'warn'})
await server.listen()
const browser=await chromium.launch({headless:true,args:process.platform==='linux'?['--no-sandbox']:[]})
const page=await browser.newPage({viewport:{width:1280,height:820}});page.setDefaultTimeout(20000)
const errors=[],checks=[];page.on('pageerror',e=>errors.push(e.message))
try{
 await page.goto(server.resolvedUrls.local[0]+'scripts/e2e/research-audit-inspector.html',{waitUntil:'networkidle',timeout:90000})
 await page.getByRole('button',{name:'科研审计',exact:true}).click()
 await page.getByRole('region',{name:'紧凑审计列表'}).waitFor()
 assert.equal(await page.locator('.record-compact-row').count(),20)
 assert.equal(await page.locator('.record-inspector').count(),0)
 assert.equal(await page.getByText('FULL_SOURCE_PAYLOAD',{exact:false}).count(),0)
 checks.push('one command opens production global overlay; twenty rows; no raw payload mounted')
 await page.screenshot({path:path.join(out,'overview-light.png')})
 await page.getByRole('button',{name:'查看 运行重复对照',exact:true}).click()
 await page.getByRole('region',{name:'记录详情'}).waitFor()
 assert.notEqual(await page.locator('[data-record-id="record-2"]').evaluate(e=>getComputedStyle(e).backgroundColor),'rgba(0, 0, 0, 0)')
 assert.ok((await page.locator('[data-record-id="record-2"]').innerText()).includes('失败 1'))
 await page.getByRole('button',{name:'原始依据',exact:true}).click()
 await page.getByText('退出码 7',{exact:false}).waitFor()
 assert.equal(await page.getByText('FULL_SOURCE_PAYLOAD',{exact:false}).count(),0)
 await page.getByText('结果与输出（1 项）',{exact:true}).click()
 await page.getByText('FULL_SOURCE_PAYLOAD',{exact:false}).first().waitFor()
 checks.push('failed row keeps negative/open badges and lazy paged original output')
 await page.getByRole('button',{name:'关闭记录详情'}).click()
 await page.getByRole('button',{name:'查看 生成参数扫描图',exact:true}).click()
 assert.equal(await page.evaluate(()=>window.auditFixture.calls.filter(c=>c.action==='artifact-versions.read').length),0)
 await page.getByRole('button',{name:'图片 / 图表',exact:true}).click()
 await page.getByRole('img',{name:'来源图像 1'}).waitFor()
 const read=await page.evaluate(()=>window.auditFixture.calls.filter(c=>c.action==='artifact-versions.read').at(-1))
 assert.equal(read.workspace,'/synthetic/science');assert.equal(read.input.expectedRef.versionId,'artifact-version:synthetic-figure-v1')
 await page.screenshot({path:path.join(out,'image-inspector-light.png')})
 checks.push('image bytes load only on selected tab, through exact expectedRef; navigation keeps version and digest')
 await page.evaluate(()=>document.documentElement.setAttribute('data-theme','dark'))
 await page.screenshot({path:path.join(out,'image-inspector-dark.png')})
 for(const width of [800,480,320]){
  await page.setViewportSize({width,height:760})
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true)
  const pane=await page.locator('.record-inspector').boundingBox();assert.ok(pane.width<=width)
  await page.screenshot({path:path.join(out,`inspector-${width}.png`)})
 }
 checks.push('dark/light and 800/480/320px views keep detail and controls within viewport')
 for(const mode of ['denied','mismatch']){
  await page.getByRole('button',{name:'关闭记录详情'}).click()
  await page.evaluate(mode=>{window.auditFixture.previewMode=mode},mode)
  await page.getByRole('button',{name:'查看 生成参数扫描图',exact:true}).click()
  await page.getByRole('button',{name:'图片 / 图表',exact:true}).click()
  await page.getByRole('alert').filter({hasText:mode==='denied'?'当前图像无读取权限':'返回版本与来源引用不一致'}).waitFor()
  assert.equal(await page.locator('.record-image-preview img').count(),0)
 }
 checks.push('denied or mismatched exact versions never show an image or infer another artifact')
 await page.getByRole('button',{name:'关闭记录详情'}).click()
 await page.evaluate(()=>{window.auditFixture.previewMode='normal'})
 await page.getByRole('button',{name:'查看 生成参数扫描图',exact:true}).click()
 await page.getByRole('button',{name:'图片 / 图表',exact:true}).click()
 await page.getByRole('img',{name:'来源图像 1'}).waitFor()
 await page.getByRole('button',{name:'打开精确版本',exact:true}).click()
 const resource=await page.evaluate(()=>window.auditFixture.resources.at(-1))
 assert.equal(resource.resource.resourceId,'artifact-version:synthetic-figure-v1');assert.ok(resource.resource.integrity.expectedDigest.startsWith('sha256:'))
 await page.getByRole('button',{name:'科研审计',exact:true}).click()
 await page.getByRole('button',{name:'关闭记录详情'}).click()
 await page.getByRole('button',{name:'后一组',exact:true}).click()
 assert.equal(await page.locator('.record-compact-row').count(),20)
 assert.equal(await page.locator('[data-record-id="record-0"]').count(),0)
 await page.getByRole('button',{name:'定位 明确比较条件',exact:true}).click()
 await page.getByRole('button',{name:'关闭记录详情'}).click()
 assert.equal(await page.locator('[data-record-id="record-0"]').count(),1)
 checks.push('window navigation replaces rows; page strip returns to the exact member')
 await page.evaluate(()=>{window.auditFixture.previewMode='detail-denied'})
 await page.getByRole('button',{name:'查看 准备匹配基线',exact:true}).click()
 const inspector=page.getByRole('region',{name:'记录详情'})
 await inspector.getByRole('alert').filter({hasText:'详情读取被拒绝'}).waitFor()
 assert.equal(await inspector.getByText('正在读取…',{exact:true}).count(),0)
 await page.evaluate(()=>{window.auditFixture.previewMode='normal'})
 await inspector.getByRole('button',{name:'重试读取详情',exact:true}).click()
 await inspector.getByRole('button',{name:'原始依据',exact:true}).click()
 await inspector.getByText('来源一致',{exact:true}).waitFor()
 await inspector.getByRole('button',{name:'关闭记录详情',exact:true}).focus()
 await page.keyboard.press('Escape')
 assert.equal(await page.locator('.record-inspector').count(),0)
 checks.push('detail permission failure remains local, retry recovers and Escape returns to the list')
 assert.deepEqual(errors,[])
 await writeFile(path.join(out,'result.json'),JSON.stringify({ok:true,checks,errors,boundary:'Production UI and contracts; synthetic record and version owner responses, not real installed plugin or model acceptance.'},null,2))
 console.log(JSON.stringify({ok:true,checks}))
}catch(e){await page.screenshot({path:path.join(out,'failure.png')}).catch(()=>{});await writeFile(path.join(out,'result.json'),JSON.stringify({ok:false,checks,errors,error:String(e)},null,2));throw e}
finally{await browser.close();await server.close()}
